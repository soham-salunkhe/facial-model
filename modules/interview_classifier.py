"""
modules/interview_classifier.py
━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━━
Interview state classification via XGBoost + calibrated probabilities.

Responsibilities
----------------
- Load or auto-train the XGBoost classifier on first run.
- Accept a 22-D feature vector and output probability estimates for
  5 interview states: Confident, Nervous, Confused, Stressed, Happy.
- Apply rolling temporal smoothing to output probabilities.
- Expose `predict()` as the primary inference interface.

Model architecture
------------------
XGBClassifier wrapped in CalibratedClassifierCV (isotonic regression)
to produce reliable probability estimates. Trained on synthetic data
generated by training/synthetic_data.py.
"""

from __future__ import annotations

import os
import pickle
from collections import deque
from typing import Dict

import numpy as np

import config as cfg


class InterviewClassifier:
    """
    XGBoost-based interview state classifier with temporal smoothing.

    Parameters
    ----------
    smooth_frames : int
        Number of frames over which to average output probabilities.
    auto_train : bool
        If True and no saved model is found, auto-generate training data
        and train a new model (takes ~2 seconds).
    """

    def __init__(
        self,
        smooth_frames: int = cfg.STATE_SMOOTH_FRAMES,
        auto_train: bool = True,
    ) -> None:
        self._smooth_frames = smooth_frames
        self._history: deque[Dict[str, float]] = deque(maxlen=smooth_frames)
        self._model = None
        self._scaler = None

        self._load_or_train(auto_train)

    # ── Model lifecycle ──────────────────────────────────────────────────────

    def _load_or_train(self, auto_train: bool) -> None:
        """Load cached model or trigger training."""
        os.makedirs(cfg.MODEL_DIR, exist_ok=True)

        if os.path.exists(cfg.CLASSIFIER_PATH) and os.path.exists(cfg.SCALER_PATH):
            try:
                with open(cfg.CLASSIFIER_PATH, "rb") as f:
                    self._model = pickle.load(f)
                with open(cfg.SCALER_PATH, "rb") as f:
                    self._scaler = pickle.load(f)
                print("[InterviewClassifier] Loaded cached model.")
                return
            except Exception as e:
                print(f"[InterviewClassifier] Failed to load model: {e}. Retraining…")

        if auto_train:
            self._train_and_save()

    def _train_and_save(self) -> None:
        """Generate synthetic data and train + save the model."""
        print("[InterviewClassifier] Generating synthetic training data…")
        from training.synthetic_data import generate  # type: ignore
        X, y = generate(n_samples=6000, seed=42)

        from sklearn.preprocessing import StandardScaler   # type: ignore
        from sklearn.calibration import CalibratedClassifierCV  # type: ignore
        from xgboost import XGBClassifier  # type: ignore

        print("[InterviewClassifier] Training XGBoost classifier…")
        scaler = StandardScaler()
        X_scaled = scaler.fit_transform(X)

        base = XGBClassifier(
            n_estimators=200,
            max_depth=5,
            learning_rate=0.08,
            subsample=0.8,
            colsample_bytree=0.8,
            eval_metric="mlogloss",
            random_state=42,
            n_jobs=-1,
        )
        model = CalibratedClassifierCV(base, method="isotonic", cv=3)
        model.fit(X_scaled, y)

        with open(cfg.CLASSIFIER_PATH, "wb") as f:
            pickle.dump(model, f)
        with open(cfg.SCALER_PATH, "wb") as f:
            pickle.dump(scaler, f)

        self._model  = model
        self._scaler = scaler
        print("[InterviewClassifier] Model trained and cached to models/.")

    # ── Inference ────────────────────────────────────────────────────────────

    def predict(self, feature_vector: np.ndarray) -> Dict[str, float]:
        """
        Predict interview state probabilities for a single feature vector.

        Parameters
        ----------
        feature_vector : np.ndarray  shape (22,)

        Returns
        -------
        Dict[str, float]
            Keys: Confident, Nervous, Confused, Stressed, Happy
            Values: 0–100 (percentage)
        """
        if self._model is None or self._scaler is None:
            return {s: 20.0 for s in cfg.STATE_LABELS}  # flat prior fallback

        x = self._scaler.transform(feature_vector.reshape(1, -1))
        proba = self._model.predict_proba(x)[0]  # shape (5,)

        raw: Dict[str, float] = {
            cfg.STATE_LABELS[i]: float(proba[i]) * 100.0
            for i in range(len(cfg.STATE_LABELS))
        }

        # ── Temporal smoothing ────────────────────────────────────────────
        self._history.append(raw)
        smoothed: Dict[str, float] = {}
        for state in cfg.STATE_LABELS:
            smoothed[state] = float(
                np.mean([h[state] for h in self._history])
            )

        # Renormalise to 100%
        total = sum(smoothed.values()) or 1.0
        for state in smoothed:
            smoothed[state] = round(smoothed[state] / total * 100.0, 1)

        return smoothed

    @property
    def is_ready(self) -> bool:
        return self._model is not None and self._scaler is not None
